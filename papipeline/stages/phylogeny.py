"""Stage 10 - phylogenomics.

Responsibilities:

* summarise the core-gene and core-SNP alignments;
* parse the newick tree and extract tip labels;
* **validate that the tree tip set matches the master sample manifest
  exactly** - no extra tips, no missing tips, no duplicates;
* **produce `lineage_label`**, which is what the lineage-aware stages consume.

That last item exists because nothing produced it. `build_tree_outputs` wrote
`sample_id` / `tree_tip_label` / `source` and passed the two-column
`REQUIRED_TREE_METADATA` to `write_tsv`, so the contract's five columns
(`docs/data_contract.md`) and the written columns disagreed, `extrasaction`
dropped the extras silently - `lineage_label`, `st` *and* `source` - and
`load_tree_metadata` then read every sample as the literal string `"unknown"`.
A reader who installed panaroo and fixed gubbins arrived at that wall with every
explanation the refusal message offered already exhausted.

Ruling R4: **`lineage_label` IS the MLST sequence type from stage 3**, read from
that stage's own on-disk table at its contracted path, and the method is
recorded so a result always says how its lineages were defined. Cutting the
tree into clades is deferred and is not implemented here; `lineage.method`
accepts one value, and `LineageConfig` refuses anything else at load time.

The alignment check above is the reason this module exists. A phylogenetic tree
whose tips do not correspond one-to-one with the samples in the manifest will
silently corrupt every lineage-aware analysis downstream (stages 13, 14 and
the annotated tree figure), so a mismatch is a hard failure with a precise
diff rather than a warning.

Alignment and tree building themselves are delegated to Panaroo, SNP-sites
and IQ-TREE 2, which are invoked by the adapter layer when installed.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Sequence, Set, Tuple

from ..config.loader import PipelineConfig
